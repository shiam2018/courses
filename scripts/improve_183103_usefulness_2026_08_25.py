def api_post(path, token, wrapper_key, body):
    payload = json.dumps({wrapper_key: body}).encode("utf-8")
    req = urllib.request.Request(f"{API}/{path}", data=payload, method="POST")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def update_step(step_id, html, token):
    live = api_get(f"step-sources/{step_id}", token)["step-sources"][0]
    live["block"]["text"] = html
    status, resp = api_put(f"step-sources/{step_id}", token, {"stepSource": live})
    if status != 200:
        raise RuntimeError(f"step {step_id}: {status} {resp}")
    print(f"updated step-source {step_id}")


def update_choice_texts(step_id, replacements, token):
    live = api_get(f"step-sources/{step_id}", token)["step-sources"][0]
    source = live["block"].get("source") or {}
    changed = False
    for option in source.get("options", []):
        if option.get("text") in replacements:
            option["text"] = replacements[option["text"]]
            changed = True
    if not changed:
        print(f"choice step-source {step_id}: no matching options")
        return
    live["block"]["source"] = source
    status, resp = api_put(f"step-sources/{step_id}", token, {"stepSource": live})
    if status != 200:
        raise RuntimeError(f"choice step {step_id}: {status} {resp}")
    print(f"updated choice step-source {step_id}")


