def set_fields(course_id, fields, token):
    course = api_get(f"courses/{course_id}", token)["courses"][0]
    course.update(fields)
    api_put(f"courses/{course_id}", token, {"course": course})
    time.sleep(2)
    fresh = api_get(f"courses/{course_id}", token)["courses"][0]
    for k, v in fields.items():
        got = fresh.get(k)
        status = "OK" if got == v else "MISMATCH"
        shown = got if not isinstance(got, str) or len(got) < 80 else got[:80] + "..."
        print(f"[{status}] {course_id}.{k} = {shown!r}")


def main():
    load_env()
    token = get_token()
    print("--- FREE 183101 ---")
    set_fields(FREE_ID, FREE_FIELDS, token)
    print("\n--- PAID 183096 ---")
