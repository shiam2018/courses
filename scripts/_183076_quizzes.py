def main():
    load_env()
    token = get_token()

    for lesson_id, questions in QUIZZES.items():
        assert len(questions) == 10, f"lesson {lesson_id}: {len(questions)} questions, need 10"

        resp = api_post("step-sources", token, "stepSource", {
            "lesson": lesson_id,
            "position": 1,
            "block": {"name": "text", "text": QUIZ_INTRO_TPL},
        })
        print(f"lesson {lesson_id}: intro step {resp['step-sources'][0]['id']}")

        for i, (qtext, options) in enumerate(questions, start=2):
            resp = api_post("step-sources", token, "stepSource", {
                "lesson": lesson_id,
                "position": i,
                "block": {
                    "name": "choice",
                    "text": f"<p>{qtext}</p>",
                    "source": {
                        "is_multiple_choice": False,
                        "is_always_correct": False,
                        "sample_size": len(options),
                        "preserve_order": False,
                        "is_html_enabled": True,
                        "is_options_feedback": False,
                        "options": [
                            {"is_correct": bool(correct), "text": text, "feedback": ""}
                            for text, correct in options
                        ],
                    },
                },
            })
            step = resp["step-sources"][0]
            print(f"  q{i-1} -> step {step['id']}")


if __name__ == "__main__":
    main()
