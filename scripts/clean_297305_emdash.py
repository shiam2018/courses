def main():
    load_env()
    token = get_token()

    total_changed = 0
    for step_id, pairs in REPLACEMENTS.items():
        step = api_get(f"steps/{step_id}", token)["steps"][0]
        text = step["block"]["text"]
        for old, new in pairs:
            assert old in text, f"step {step_id}: anchor not found: {old[:70]!r}"
            text = text.replace(old, new)
        remaining = text.count("—")
        step["block"]["text"] = text
        api_put(f"step-sources/{step_id}", token, {"stepSource": {"block": step["block"]}})
        total_changed += 1
        print(f"step {step_id}: fixed, remaining em-dash: {remaining}")

    print(f"\nDone. {total_changed} steps updated.")


if __name__ == "__main__":
    main()
