def main():
    load_env()
    token = get_token()

    for step_id in STEP_IDS:
        live = api_get(f"step-sources/{step_id}", token)
        step_sources = live.get("step-sources") or live.get("stepSources")
        live_obj = step_sources[0]
        text = live_obj["block"]["text"]
        original = text

        if BOILERPLATE_OLD in text:
            text = text.replace(BOILERPLATE_OLD, BOILERPLATE_NEW)

        for old, new in SPECIFIC.get(step_id, []):
            if old not in text:
                print(f"[WARN] step={step_id}: anchor not found: {old[:50]!r}")
                continue
            text = text.replace(old, new)

        remaining = text.count("—")
        if remaining:
            print(f"[STILL HAS DASHES] step={step_id}: {remaining}")

        if text == original:
            print(f"[NOCHANGE] step={step_id}")
            continue

        live_obj["block"]["text"] = text
        status, resp = api_put(f"step-sources/{step_id}", token, {"stepSource": live_obj})
        print(f"[{'OK' if status == 200 else 'FAIL'}] step={step_id} status={status}")
        time.sleep(1)


if __name__ == "__main__":
    main()
