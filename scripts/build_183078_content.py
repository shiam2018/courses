def push_lesson(lesson_id, html, token):
    resp = api_post("step-sources", token, "stepSource", {
        "lesson": lesson_id,
        "position": 1,
        "block": {"name": "text", "text": html},
    })
    print(f"lesson {lesson_id}: text step {resp['step-sources'][0]['id']}")


def push_quiz(lesson_id, intro_html, questions, token):
    resp = api_post("step-sources", token, "stepSource", {
        "lesson": lesson_id,
        "position": 1,
        "block": {"name": "text", "text": intro_html},
    })
    print(f"lesson {lesson_id}: quiz intro step {resp['step-sources'][0]['id']}")
    for i, q in enumerate(questions, start=2):
        options = q["options"]
        resp = api_post("step-sources", token, "stepSource", {
            "lesson": lesson_id,
            "position": i,
            "block": {
                "name": "choice",
                "text": q["text"],
                "source": {
                    "is_multiple_choice": False,
                    "is_always_correct": False,
                    "sample_size": len(options),
                    "preserve_order": False,
                    "is_html_enabled": True,
                    "is_options_feedback": False,
                    "options": [
                        {"is_correct": bool(o.get("correct")), "text": o["text"], "feedback": ""}
                        for o in options
                    ],
                },
            },
        })
        print(f"lesson {lesson_id}: choice step {resp['step-sources'][0]['id']} at position {i}")


def main():
    load_env()
    token = get_token()

    for lesson_id, html in LESSONS.items():
        push_lesson(lesson_id, html, token)

    for lesson_id, (intro_html, questions) in QUIZZES.items():
        assert len(questions) == 10, f"lesson {lesson_id}: expected 10 questions, got {len(questions)}"
        for q in questions:
            assert len(q["options"]) == 4, f"lesson {lesson_id}: expected 4 options"
            assert sum(1 for o in q["options"] if o.get("correct")) == 1, f"lesson {lesson_id}: expected exactly 1 correct"
        push_quiz(lesson_id, img(lesson_id) + intro_html, questions, token)

    print("\nDone.")


if __name__ == "__main__":
    main()
