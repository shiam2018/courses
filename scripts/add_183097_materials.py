#!/usr/bin/env python3
"""Create the 'Полезные материалы' lesson for course 183097 (Профессия
таргетолог), attach it as the last unit in section 743918 ('Что дальше'),
and push its text content."""
import sys
sys.path.insert(0, "/Users/igorshenshin/Developer/Web/Stepik/courses/scripts")
from stepik_create_module import api_post  # noqa: E402
from stepik_push import load_env, get_token  # noqa: E402

SECTION_ID = 743918

TEXT = '''<h2>Полезные материалы</h2>
<p>Здесь собран рабочий комплект курса в одном месте: не конспект, а шаблоны и чек-листы, которые можно скопировать и заполнить под свой проект или первого клиента.</p>

<h2>1. Бриф на рекламную кампанию</h2>
<blockquote>
<p>Бизнес и продукт: [что рекламируем]. Цель кампании и одна главная метрика успеха: [заявка/продажа/подписка]. Целевая аудитория: [кто это и какую задачу решает]. Оффер: [почему именно это предложение]. Бюджет и сроки теста: [сумма и период]. Ограничения: [что нельзя показывать или обещать].</p>
</blockquote>

<h2>2. Формулы ключевых метрик</h2>
<table>
<thead><tr><th>Метрика</th><th>Формула</th><th>Вопрос, на который отвечает</th></tr></thead>
<tbody>
<tr><td>CTR</td><td>Клики / Показы × 100%</td><td>Цепляет ли креатив внимание</td></tr>
<tr><td>CPM</td><td>Бюджет / Показы × 1000</td><td>Сколько стоит охват тысячи человек</td></tr>
<tr><td>CPC</td><td>Бюджет / Клики</td><td>Сколько стоит один переход</td></tr>
<tr><td>CPA</td><td>Бюджет / Заявки</td><td>Сколько стоит одна заявка</td></tr>
<tr><td>ROAS</td><td>Доход / Расход × 100%</td><td>Окупается ли кампания</td></tr>
</tbody>
</table>

<h2>3. Чек-лист структуры кампании перед запуском</h2>
<ol>
<li>Цель кампании и главная метрика зафиксированы до запуска, а не после первых цифр.</li>
<li>Аудитория разбита на сегменты, а не собрана в одну широкую группу без причины.</li>
<li>Минимум 2-3 варианта креатива готовы для теста, а не один «на удачу».</li>
<li>Пиксель или счётчик установлен и цель проверена тестовым переходом.</li>
<li>Дневной бюджет выставлен осознанно, с расчётом на срок теста.</li>
</ol>

<h2>4. Шаблон текста объявления</h2>
<blockquote>
<p>Заголовок: [конкретная выгода или боль аудитории, без общих слов]. Текст: [что получит человек] + [почему сейчас, а не потом]. Призыв к действию: [конкретное действие: узнать цену, оставить заявку, записаться]. Визуал: [что на картинке или видео и как это связано с текстом].</p>
</blockquote>

<h2>5. Чек-лист решения по кампании после первых данных</h2>
<ul>
<li>Показов много, кликов мало: проблема в креативе или аудитории, не в посадочной.</li>
<li>Кликов много, заявок нет: проблема в посадочной странице или оффере, не в рекламе.</li>
<li>CPA держится ниже целевого несколько дней подряд: можно осторожно увеличивать бюджет.</li>
<li>CPA выше целевого и не снижается: остановить и пересмотреть аудиторию или оффер, а не «подождать ещё».</li>
</ul>

<h2>6. Структура кейса для портфолио без клиентов</h2>
<ol>
<li>Задача: что нужно было бы решить (свой проект, учебный кейс или тестовое задание).</li>
<li>Что сделали: аудитория, оффер, структура кампании, креативы.</li>
<li>Как оценивали результат: какие метрики и почему именно они.</li>
<li>Результат или прогноз: цифра, если кампания реально запускалась, либо обоснованный расчёт.</li>
<li>Что бы изменили при повторном запуске.</li>
</ol>

<h2>Финальное задание</h2>
<p>Соберите один сквозной документ: бриф из пункта 1, прогноз по формулам из пункта 2, чек-лист запуска из пункта 3 и один готовый вариант объявления по шаблону из пункта 4. Это уже конкретный артефакт, который можно показать на собеседовании или клиенту, а не просто пройденная тема курса.</p>
'''


def main():
    load_env()
    token = get_token()

    lesson_resp = api_post("lessons", token, "lesson", {
        "title": "Полезные материалы",
        "language": "ru",
    })
    lesson_id = lesson_resp["lessons"][0]["id"]
    print("lesson created:", lesson_id)

    step_resp = api_post("step-sources", token, "stepSource", {
        "lesson": lesson_id,
        "position": 1,
        "block": {"name": "text", "text": TEXT},
    })
    step_id = step_resp["step-sources"][0]["id"]
    print("step-source created:", step_id)

    unit_resp = api_post("units", token, "unit", {
        "section": SECTION_ID,
        "lesson": lesson_id,
        "position": 4,
    })
    unit_id = unit_resp["units"][0]["id"]
    print("unit created:", unit_id)

    import json
    json.dump(
        {"lesson_id": lesson_id, "step_id": step_id, "unit_id": unit_id},
        open("/Users/igorshenshin/Developer/Web/Stepik/courses/scripts/_183097_materials.json", "w"),
        indent=2,
    )


if __name__ == "__main__":
    main()
