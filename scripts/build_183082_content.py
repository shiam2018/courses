def push_lesson(lesson_id, html, token):
    resp = api_post("step-sources", token, "stepSource", {
        "lesson": lesson_id,
        "position": 1,
        "block": {"name": "text", "text": html},
    })
    print(f"lesson {lesson_id}: text step {resp['step-sources'][0]['id']}")


