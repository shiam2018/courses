def main():
    load_env()
    token = get_token()

    for step_id, pairs in REPLACEMENTS.items():
        step = api_get(f"steps/{step_id}", token)["steps"][0]
        text = step["block"]["text"]
        for old, new in pairs:
            assert old in text, f"step {step_id}: anchor not found: {old[:60]!r}"
            text = text.replace(old, new)
        remaining = text.count("—")
        step["block"]["text"] = text
        api_put(f"step-sources/{step_id}", token, {"stepSource": {"block": step["block"]}})
        print(f"step {step_id}: fixed, remaining em-dash in text: {remaining}")

    # fix lesson 2548393 title
    lesson = api_get("lessons/2548393", token)["lessons"][0]
    old_title = lesson["title"]
    new_title = old_title.replace("Связка запрос — объявление — страница", "Связка запрос → объявление → страница")
    if new_title != old_title:
        lesson["title"] = new_title
        api_put("lessons/2548393", token, {"lesson": lesson})
        print(f"lesson 2548393 title: {old_title!r} -> {new_title!r}")


if __name__ == "__main__":
    main()
