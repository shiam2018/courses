def api_post(path, token, wrapper_key, body):
    payload = json.dumps({wrapper_key: body}).encode("utf-8")
    req = urllib.request.Request(f"{API}/{path}", data=payload, method="POST")
    req.add_header("Authorization", f"Bearer {token}")
    req.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def update_step(step_id, html, token):
    live = api_get(f"step-sources/{step_id}", token)["step-sources"][0]
    live["block"]["text"] = html
    status, resp = api_put(f"step-sources/{step_id}", token, {"stepSource": live})
    if status != 200:
        raise RuntimeError(f"step {step_id}: {status} {resp}")
    print(f"updated step-source {step_id}")


def get_final_section_lessons(token):
    section = api_get(f"sections/{FINAL_SECTION_ID}", token)["sections"][0]
    lessons = []
    for unit_id in section.get("units") or []:
        unit = api_get(f"units/{unit_id}", token)["units"][0]
        lesson = api_get(f"lessons/{unit['lesson']}", token)["lessons"][0]
        lessons.append({"unit": unit, "lesson": lesson})
    return lessons


def ensure_materials_lesson(token):
    existing = get_final_section_lessons(token)
    for item in existing:
        if item["lesson"].get("title") == "Полезные материалы":
            print(f"materials lesson already exists: {item['lesson']['id']}")
            return item["lesson"]["id"]
    lesson_resp = api_post("lessons", token, "lesson", {
        "title": "Полезные материалы",
        "language": "ru",
        "steps": [],
    })
    lesson = lesson_resp["lessons"][0]
    step_resp = api_post("step-sources", token, "stepSource", {
        "lesson": lesson["id"],
        "position": 1,
        "block": {"name": "text", "text": MATERIALS_HTML},
    })
    position = max([item["unit"]["position"] for item in existing] or [0]) + 1
    unit_resp = api_post("units", token, "unit", {
        "section": FINAL_SECTION_ID,
        "lesson": lesson["id"],
        "position": position,
    })
    print(
        f"created materials lesson {lesson['id']}, "
        f"step-source {step_resp['step-sources'][0]['id']}, "
        f"unit {unit_resp['units'][0]['id']}"
    )
    return lesson["id"]


