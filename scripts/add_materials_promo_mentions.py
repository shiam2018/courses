def main():
    load_env()
    token = get_token()

    for cid, (old, new) in INSERTIONS.items():
        course = api_get(f"courses/{cid}", token)["courses"][0]
        desc = course["description"]
        if old not in desc:
            print(f"[FAIL] {cid}: anchor paragraph not found, skipping")
            continue
        if "Полезные материалы" in desc or "рабочая папка" in desc or "комплект" in desc or "шпаргалка" in desc:
            print(f"[SKIP] {cid}: already mentions materials")
            continue
        course["description"] = desc.replace(old, new)
        api_put(f"courses/{cid}", token, {"course": course})
        time.sleep(2)
        fresh = api_get(f"courses/{cid}", token)["courses"][0]
        ok = new in fresh["description"]
        print(f"[{'OK' if ok else 'MISMATCH'}] {cid}")


if __name__ == "__main__":
    main()
