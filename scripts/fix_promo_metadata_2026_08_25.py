def main():
    load_env()
    token = get_token()
    results = []

    for course_id, fields in UPDATES.items():
        for key, value in fields.items():
            if isinstance(value, str) and "—" in value:
                raise ValueError(f"{course_id}.{key}: em dash found")

        course = api_get(f"courses/{course_id}", token)["courses"][0]
        before = {key: course.get(key) for key in fields}
        course.update(fields)
        status, resp = api_put(f"courses/{course_id}", token, {"course": course})
        if status != 200:
            raise RuntimeError(f"{course_id}: {status} {resp}")
        results.append({
            "id": course_id,
            "title": course.get("title"),
            "fields": sorted(fields),
            "before": before,
            "after": fields,
        })
        print(f"{course_id}: updated {', '.join(sorted(fields))}")

    out = os.path.join(os.path.dirname(__file__), "_promo_metadata_fixes_2026_08_25.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f"saved {out}")


if __name__ == "__main__":
    main()
