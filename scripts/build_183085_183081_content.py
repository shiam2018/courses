def create_steps(course_id, manifest, header_urls, token):
    content_dir = os.path.join(WORK_ROOT, str(course_id), "content")
    os.makedirs(content_dir, exist_ok=True)
    for sec in manifest["sections"]:
        section_title = sec["title"]
        for lesson in sec["lessons"]:
            lid = lesson["id"]
            title, _, intro, practical, transition, *kind = lesson["lesson_data"]
            if kind and kind[0] == "quiz":
                intro_html = lesson_html(course_id, header_urls[lid], title, intro, practical, transition)
                intro_path = os.path.join(content_dir, f"{lid}-intro.html")
                q_path = os.path.join(content_dir, f"{lid}-questions.json")
                with open(intro_path, "w", encoding="utf-8") as f:
                    f.write(intro_html)
                with open(q_path, "w", encoding="utf-8") as f:
                    json.dump(quiz_questions(course_id, section_title), f, ensure_ascii=False, indent=2)
                subprocess.run([
                    "python3", os.path.join(ROOT, "scripts", "create_choice_steps.py"),
                    str(lid), q_path, intro_path,
                ], check=True)
            else:
                body = lesson_html(course_id, header_urls[lid], title, intro, practical, transition)
                path = os.path.join(content_dir, f"{lid}.html")
                with open(path, "w", encoding="utf-8") as f:
                    f.write(body)
                subprocess.run([
                    "python3", os.path.join(ROOT, "scripts", "push_text_step.py"),
                    str(lid), path,
                ], check=True)
            time.sleep(0.5)


def push_icons(course_id, cfg, manifest):
    mapping = []
    icon_cycle = cfg["icons"]
    idx = 0
    for sec in manifest["sections"]:
        for lesson in sec["lessons"]:
            icon = "approval" if "Проверка знаний" in lesson["title"] else icon_cycle[idx % len(icon_cycle)]
            mapping.append({"lesson_id": lesson["id"], "icon": icon})
            idx += 1
    path = os.path.join(WORK_ROOT, str(course_id), "icon-mapping.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(mapping, f, ensure_ascii=False, indent=2)
    subprocess.run(["python3", os.path.join(ROOT, "scripts", "push_lesson_icons.py"), path], check=True)


