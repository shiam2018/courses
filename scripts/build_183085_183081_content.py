def generate_and_upload_headers(course_id, manifest):
    html_dir = os.path.join(WORK_ROOT, str(course_id), "headers_html")
    png_dir = os.path.join(WORK_ROOT, str(course_id), "headers_png")
    webp_dir = os.path.join(WORK_ROOT, str(course_id), "headers_webp")
    os.makedirs(html_dir, exist_ok=True)
    os.makedirs(png_dir, exist_ok=True)
    os.makedirs(webp_dir, exist_ok=True)

    lesson_headers = []
    for sec in manifest["sections"]:
        for lesson in sec["lessons"]:
            title = lesson["title"]
            label = lesson["label"]
            lid = lesson["id"]
            path = os.path.join(html_dir, f"header-{lid}.html")
            with open(path, "w", encoding="utf-8") as f:
                f.write(header_html(label, title))
            lesson_headers.append((lid, title))

    subprocess.run([
        "node", os.path.join(ROOT, "scripts", "render_batch.mjs"),
        html_dir, png_dir, "1920", "420",
    ], check=True)

    urls = {}
    for lid, _ in lesson_headers:
        png = os.path.join(png_dir, f"header-{lid}.png")
        webp = os.path.join(webp_dir, f"header-{lid}.webp")
        subprocess.run(["cwebp", "-q", "82", png, "-o", webp], check=True, stdout=subprocess.DEVNULL)
        url, _ = upload_attachment(str(course_id), webp, f"header-{lid}.webp")
        urls[lid] = url
        print(f"header {lid} -> {url}")
    return urls


