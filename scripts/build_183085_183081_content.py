def api_delete(path, token):
    req = urllib.request.Request(f"{API}/{path}", method="DELETE")
    req.add_header("Authorization", f"Bearer {token}")
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.status


def update_course_metadata(course_id, cfg, token):
    course = api_get(f"courses/{course_id}", token)["courses"][0]
    course.update({
        "title": cfg["title"],
        "summary": cfg["summary"],
        "description": cfg["description"],
        "target_audience": cfg["target_audience"],
        "requirements": cfg["requirements"],
        "acquired_skills": cfg["acquired_skills"],
        "learning_format": cfg["learning_format"],
        "workload": cfg["workload"],
        "language": "ru",
        "is_paid": False,
    })
    status, resp = api_put(f"courses/{course_id}", token, {"course": course})
    if status != 200:
        raise RuntimeError(f"course {course_id} metadata failed: {status} {resp}")
    print(f"metadata OK {course_id}")


def build_skeleton(course_id, cfg, token):
    course = api_get(f"courses/{course_id}", token)["courses"][0]
    if course.get("total_units", 0):
        raise RuntimeError(f"course {course_id} is not empty: total_units={course.get('total_units')}")

    created = {"sections": []}
    for sec_pos, (section_title, section_desc, lessons) in enumerate(cfg["sections"], start=1):
        section = api_post("sections", token, "section", {
            "course": course_id,
            "title": section_title,
            "position": sec_pos,
            "units": [],
            "description": section_desc,
        })["sections"][0]
        sec_record = {
            "id": section["id"],
            "title": section_title,
            "description": section_desc,
            "lessons": [],
        }
        print(f"[{course_id}] section {section['id']}: {section_title}")

        for lesson_pos, lesson_data in enumerate(lessons, start=1):
            title = lesson_data[0]
            if len(title) > 64:
                raise ValueError(f"lesson title too long ({len(title)}): {title}")
            lesson = api_post("lessons", token, "lesson", {
                "title": title,
                "language": "ru",
                "steps": [],
            })["lessons"][0]
            unit = api_post("units", token, "unit", {
                "section": section["id"],
                "lesson": lesson["id"],
                "position": lesson_pos,
            })["units"][0]
            sec_record["lessons"].append({
                "id": lesson["id"],
                "unit_id": unit["id"],
                "title": title,
                "label": lesson_data[1],
                "lesson_data": lesson_data,
            })
            print(f"  lesson {lesson['id']} / unit {unit['id']}: {title}")
        created["sections"].append(sec_record)
    out_path = os.path.join(os.path.dirname(__file__), f"_{course_id}_skeleton_created.json")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(created, f, ensure_ascii=False, indent=2)
    return created


