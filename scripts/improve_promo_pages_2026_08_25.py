def main():
    load_env()
    token = get_token()
    results = []
    for course_id, patch in UPDATES.items():
        course = api_get(f"courses/{course_id}", token)["courses"][0]
        before = {key: course.get(key) for key in patch}
        course.update(patch)
        status, resp = api_put(f"courses/{course_id}", token, {"course": course})
        if status != 200:
            raise RuntimeError(f"{course_id}: {status} {resp}")
        after = api_get(f"courses/{course_id}", token)["courses"][0]
